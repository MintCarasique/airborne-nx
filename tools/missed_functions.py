"""Finds function starts ReXGlue's analysis missed and writes rex/missed_functions.toml.

default.xex has no RTTI, so ReXGlue's vtable scanner finds no vtables, and functions
reached only through a vtable or another pointer (leaves, thunks) are not discovered.
They fail at run time with "[FATAL] Call to invalid or unregistered function".

The old XenonAnalyse pass (generated/ppc/ppc_func_mapping.cpp) knows most of them. A
start from that list is taken only when no ReXGlue function covers its address, so
mid-function branch targets of the old analysis are never declared as functions.

Coverage comes from the generated C++: every PowerPC instruction is one line starting
with "//", and labels loc_XXXXXXXX: give the address of each block.

Run it against a codegen made WITHOUT missed_functions.toml in the manifest includes
(otherwise everything is covered and the list comes out empty):
    python -I tools/missed_functions.py
Writes analysis/missed_functions.txt and rex/missed_functions.toml.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
GEN = ROOT / 'rex/generated/default'
IMAGE_BASE = 0x82000000

# Candidates that are data inside .text: codegen reports "has no blocks - generating
# stub" for them. Each is a two-word header ("lwz r24,-8548(0)" + an lwz) 8 bytes
# before a function ReXGlue already covers from its mflr.
DATA_IN_TEXT = ROOT / 'rex/missed_functions_data.txt'


def read_addresses(path):
    if not path.exists():
        return set()
    return {int(line.split('#')[0], 16) for line in path.read_text().splitlines()
            if line.split('#')[0].strip()}


def main():
    registered = {}
    for line in (GEN / 'airborne_register.cpp').open(errors='replace'):
        m = re.search(r'SetFunction\(0x([0-9A-Fa-f]{8}),\s*(\w+)\)', line)
        if m:
            registered[m.group(2)] = int(m.group(1), 16)
    starts = set(registered.values())

    covered = set()
    define = re.compile(r'DEFINE_REX_FUNC\((\w+)\)\s*\{')
    label = re.compile(r'^loc_([0-9A-Fa-f]{8}):')
    for path in sorted(GEN.glob('airborne_recomp.*.cpp')):
        cur = None
        for line in path.open(errors='replace'):
            if cur is None:
                m = define.match(line)
                if m:
                    cur = registered[m.group(1)]
                continue
            if line.rstrip('\r\n') == '}':
                cur = None
                continue
            s = line.strip()
            if s.startswith('//'):
                covered.add(cur)
                cur += 4
            else:
                m = label.match(s)
                if m:
                    cur = int(m.group(1), 16)

    mapping = (ROOT / 'generated/ppc/ppc_func_mapping.cpp').read_text(errors='replace')
    old = sorted({int(x, 16) for x in re.findall(r'\{\s*0x([0-9A-Fa-f]{8})\s*,', mapping)})
    image = (ROOT / 'analysis/image/image_loader_normalized.bin').read_bytes()
    excluded = read_addresses(DATA_IN_TEXT)
    candidates, padding, data = [], 0, 0
    for address in old:
        if address in covered or address in starts:
            continue
        offset = address - IMAGE_BASE
        if image[offset:offset + 4] == b'\0\0\0\0':
            padding += 1
            continue
        if address in excluded:
            data += 1
            continue
        candidates.append(address)

    if not candidates:
        raise SystemExit('no candidates: was codegen run with missed_functions.toml included?')
    (ROOT / 'analysis/missed_functions.txt').write_text(''.join(f'0x{a:08X}\n' for a in candidates))
    header = ('# Generated by tools/missed_functions.py - do not edit by hand.\n'
              '# Function starts from the old XenonAnalyse pass in code no ReXGlue function\n'
              '# covers: mostly leaves and thunks reached only through vtables (no RTTI).\n'
              '[functions]\n')
    (ROOT / 'rex/missed_functions.toml').write_text(header + ''.join(f'"0x{a:08X}" = {{}}\n' for a in candidates))
    print(f'covered instructions {len(covered)}, ReXGlue functions {len(starts)}, old list {len(old)}')
    print(f'dropped: {padding} zero padding, {data} data in .text; candidates {len(candidates)}')


if __name__ == '__main__':
    main()
