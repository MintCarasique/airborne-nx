#pragma once
#include <array>
#include <cstdint>
namespace airborne {
inline bool masked_point_state(const std::array<uint32_t,0x5003>& r,uint32_t initiator) {
    return initiator==0x10081 && r[0x2208]==4 && !r[0x2104] && !r[0x2200] &&
        r[0x2202]==0x87000007 && r[0x2204]==0x10000 && r[0x2205]==0x10000 && r[0x2206]==0x300 &&
        r[0x2280]==0x80008 && r[0x2281]==0x4000010 && r[0x2300]==0x400 && r[0x2302]==4 &&
        r[0x2000]==0x14000500 && !r[0x200e] && r[0x200f]==0x20002000 &&
        !r[0x2080] && !r[0x2081] && r[0x2082]==0x100010 && r[0x2324]==2;
}
}
